export async function getServerSideProps() {
  const queryClient = new QueryClient();

  /**
   * Although the signature of "prefetchQuery" allows "staleTime", it doesn't affect the query.
   * Only use the key and the query function here, no other option to be set.
   *
   * For global options see the one set in the custom app.
   * For query specific options, see the one set for the specific query in the component.
   *
   * @see https://tanstack.com/query/v4/docs/react/reference/QueryClient#queryclientprefetchquery
   */
  await queryClient.prefetchQuery({
    queryKey: [baseUrl, path, headers],
    queryFn: fetcher,
  });

  return {
    props: {
      dehydratedState: dehydrate(queryClient),
    },
  };
}
